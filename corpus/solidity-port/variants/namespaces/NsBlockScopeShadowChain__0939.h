struct NsBlockScopeShadowChain : public ContractBase
{
    struct Scratch
    {
        uint64 snapScratch;
        uint64 snapAtOne;
        uint64 snapAtTwo;
        uint64 snapAtThree;
        uint64 snapAfterBlocks;
    };

    struct StateData
    {
        struct Inner
        {
        uint64 outer;
        uint64 depthOne;
        uint64 depthTwo;
        uint64 afterAll;
        uint64 calls;
        Scratch scratch;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Snap_input
    {
        uint64 seed;
    };

    struct Snap_output {};

    PUBLIC_PROCEDURE(Snap)
    {
        state.mut().inner.scratch.snapAtOne = tier;
        {
        uint64 tier = 20;
        state.mut().inner.scratch.snapAtTwo = tier;
        {
        uint64 tier = 300;
        state.mut().inner.scratch.snapAtThree = tier;
        }
        }
        state.mut().inner.scratch.snapAfterBlocks = tier;
        state.mut().inner.outer = state.mut().inner.scratch.snapAtOne;
        state.mut().inner.depthOne = state.mut().inner.scratch.snapAtTwo;
        state.mut().inner.depthTwo = state.mut().inner.scratch.snapAtThree;
        state.mut().inner.afterAll = state.mut().inner.scratch.snapAfterBlocks;

        state.mut().inner.calls++;
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 outer;
        uint64 depthOne;
        uint64 depthTwo;
        uint64 afterAll;
        uint64 calls;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.outer = state.get().inner.outer;
        output.depthOne = state.get().inner.depthOne;
        output.depthTwo = state.get().inner.depthTwo;
        output.afterAll = state.get().inner.afterAll;
        output.calls = state.get().inner.calls;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Snap, 1);
    }
};
