struct DoWhileEmulatedWithFlag : public ContractBase
{
    struct Scratch
    {
        uint64 runValue;
        uint64 runFirst;
    };

    struct StateData
    {
        struct Inner
        {
        uint64 calls;
        uint64 difference;
        uint64 whileRuns;
        uint64 doWhileRuns;
        Scratch scratch;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Read_input {};

    struct Read_output
    {
        uint64 doWhileRuns;
        uint64 whileRuns;
        uint64 difference;
        uint64 calls;
    };

    struct Read_locals
    {
        Read_input forwardedInput;
        Read_output forwardedOutput;
    };

    PUBLIC_FUNCTION_WITH_LOCALS(Read)
    {
        CALL(ReadBody, locals.forwardedInput, locals.forwardedOutput);
        output = locals.forwardedOutput;
    }

    struct Run_input
    {
        uint64 a;
        uint64 b;
    };

    struct Run_output {};

    struct Run_locals
    {
        Run_input forwardedInput;
        Run_output forwardedOutput;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Run)
    {
        locals.forwardedInput = input;
        CALL(RunBody, locals.forwardedInput, locals.forwardedOutput);
    }

    using ReadBody_input = Read_input;

    using ReadBody_output = Read_output;

    PRIVATE_FUNCTION(ReadBody)
    {
        output.doWhileRuns = state.get().inner.doWhileRuns;
        output.whileRuns = state.get().inner.whileRuns;
        output.difference = state.get().inner.difference;
        output.calls = state.get().inner.calls;
    }

    using RunBody_input = Run_input;

    using RunBody_output = Run_output;

    PRIVATE_PROCEDURE(RunBody)
    {
        state.mut().inner.scratch.runValue = input.a;
        state.mut().inner.scratch.runFirst = 1;
        state.mut().inner.doWhileRuns = 0;
        while (state.mut().inner.scratch.runFirst != 0 || state.mut().inner.scratch.runValue > 10)
        {
        state.mut().inner.scratch.runFirst = 0;
        state.mut().inner.doWhileRuns++;
        if (state.mut().inner.scratch.runValue > 0)
        {
        state.mut().inner.scratch.runValue = QPI::div(state.mut().inner.scratch.runValue, 3ULL);
        }
        if (state.get().inner.doWhileRuns > 20)
        {
        state.mut().inner.scratch.runValue = 0;
        }
        }
        state.mut().inner.scratch.runValue = input.a;
        state.mut().inner.whileRuns = 0;
        while (state.mut().inner.scratch.runValue > 10 && state.get().inner.whileRuns < 20)
        {
        state.mut().inner.scratch.runValue = QPI::div(state.mut().inner.scratch.runValue, 3ULL);
        state.mut().inner.whileRuns++;
        }
        state.mut().inner.difference = state.get().inner.doWhileRuns - state.get().inner.whileRuns;

        state.mut().inner.calls++;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }
};
