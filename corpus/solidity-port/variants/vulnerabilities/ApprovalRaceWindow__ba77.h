struct ApprovalRaceWindow : public ContractBase
{
    struct Scratch
    {
        uint64 runFirst;
        uint64 runSecond;
    };

    struct StateData
    {
        struct Inner
        {
        uint64 calls;
        uint64 excess;
        uint64 safeMaximum;
        uint64 spentInWindow;
        uint64 allowance;
        Scratch scratch;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Run_input
    {
        uint64 a;
        uint64 b;
    };

    struct Run_output {};

    PUBLIC_PROCEDURE(Run)
    {
        state.mut().inner.scratch.runFirst = input.a;
        state.mut().inner.scratch.runSecond = input.b;
        state.mut().inner.allowance = state.mut().inner.scratch.runFirst;
        // The spender empties the old allowance, then the owner overwrites it with the new one.
        state.mut().inner.spentInWindow = state.mut().inner.scratch.runFirst + state.mut().inner.scratch.runSecond;
        state.mut().inner.allowance = state.mut().inner.scratch.runSecond;
        state.mut().inner.safeMaximum = state.mut().inner.scratch.runSecond;
        state.mut().inner.excess = state.get().inner.spentInWindow - state.get().inner.safeMaximum;

        state.mut().inner.calls++;
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 allowance;
        uint64 spentInWindow;
        uint64 safeMaximum;
        uint64 excess;
        uint64 calls;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.allowance = state.get().inner.allowance;
        output.spentInWindow = state.get().inner.spentInWindow;
        output.safeMaximum = state.get().inner.safeMaximum;
        output.excess = state.get().inner.excess;
        output.calls = state.get().inner.calls;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }

    INITIALIZE()
    {
        state.mut().inner.allowance = 0;
        state.mut().inner.spentInWindow = 0;
        state.mut().inner.safeMaximum = 0;
        state.mut().inner.excess = 0;
        state.mut().inner.calls = 0;
    }
};
