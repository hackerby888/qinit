// Stresses: the ERC20 approval race: setting a new allowance without zeroing it first, so a spender who moves in between can spend both — modelled as an ordered pair of operations with the total tracked
// Port caveat: There is no mempool to race in; the port applies the operations in the damaging order deliberately and counts what the spender could take, which is the arithmetic the incident reduces to.
