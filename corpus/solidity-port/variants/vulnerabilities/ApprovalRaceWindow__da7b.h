struct ApprovalRaceWindow : public ContractBase
{
    struct StateData
    {
        uint64 placementGuard;
        uint64 allowance;
        uint64 spentInWindow;
        uint64 safeMaximum;
        uint64 excess;
        uint64 calls;
    };

    struct Read_input {};

    struct Read_output
    {
        uint64 allowance;
        uint64 spentInWindow;
        uint64 safeMaximum;
        uint64 excess;
        uint64 calls;
    };

    struct Read_locals
    {
        Read_input forwardedInput;
        Read_output forwardedOutput;
    };

    PUBLIC_FUNCTION_WITH_LOCALS(Read)
    {
        CALL(ReadBody, locals.forwardedInput, locals.forwardedOutput);
        output = locals.forwardedOutput;
    }

    struct Run_input
    {
        uint64 a;
        uint64 b;
    };

    struct Run_output {};

    struct Run_locals
    {
        Run_input forwardedInput;
        Run_output forwardedOutput;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Run)
    {
        locals.forwardedInput = input;
        CALL(RunBody, locals.forwardedInput, locals.forwardedOutput);
    }

    using ReadBody_input = Read_input;

    using ReadBody_output = Read_output;

    PRIVATE_FUNCTION(ReadBody)
    {
        output.allowance = state.get().allowance;
        output.spentInWindow = state.get().spentInWindow;
        output.safeMaximum = state.get().safeMaximum;
        output.excess = state.get().excess;
        output.calls = state.get().calls;
    }

    using RunBody_input = Run_input;

    using RunBody_output = Run_output;

    struct RunBody_locals
    {
        uint64 first;
        uint64 second;
    };

    PRIVATE_PROCEDURE_WITH_LOCALS(RunBody)
    {
        locals.first = input.a;
        locals.second = input.b;
        state.mut().allowance = locals.first;
        // The spender empties the old allowance, then the owner overwrites it with the new one.
        state.mut().spentInWindow = locals.first + locals.second;
        state.mut().allowance = locals.second;
        state.mut().safeMaximum = locals.second;
        state.mut().excess = state.get().spentInWindow - state.get().safeMaximum;

        state.mut().calls++;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }

    INITIALIZE()
    {
        state.mut().allowance = 0;
        state.mut().spentInWindow = 0;
        state.mut().safeMaximum = 0;
        state.mut().excess = 0;
        state.mut().calls = 0;
    }
};
