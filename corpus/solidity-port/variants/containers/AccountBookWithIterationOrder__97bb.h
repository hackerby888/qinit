// Stresses: a HashMap paired with an insertion-ordered key list, so the contract can iterate deterministically — the list and the table have to stay in step through inserts, updates and one removal
// Port caveat: Solidity mappings cannot be iterated at all, which is why every contract that needs it carries this pair; the port keeps the pair and the audit that checks it.
// Variant: capacity=2 entryOrder=reversed entryShape=viaPrivate initStyle=absent placement=last stateOrder=reversed temporaries=locals
