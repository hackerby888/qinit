struct MapZeroValueVersusAbsent : public ContractBase
{
    struct Scratch
    {
        uint64 runI;
        uint64 runBound;
        uint64 runFetched;
        uint64 runHit;
        uint64 runInSet;
    };

    struct StateData
    {
        struct Inner
        {
        uint64 accumulator;
        uint64 calls;
        HashMap<uint64, uint64, 1024> values;
        HashSet<uint64, 1024> present;
        uint64 storedZeros;
        uint64 absent;
        uint64 disagreements;
        Scratch scratch;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Run_input
    {
        uint64 count;
        uint64 probe;
    };

    struct Run_output {};

    PUBLIC_PROCEDURE(Run)
    {
        state.mut().inner.scratch.runBound = input.count;
        if (state.mut().inner.scratch.runBound > 1024)
        {
        state.mut().inner.scratch.runBound = 1024;
        }
        state.mut().inner.values.reset();
        state.mut().inner.present.reset();
        state.mut().inner.storedZeros = 0;
        state.mut().inner.absent = 0;
        for (state.mut().inner.scratch.runI = 0; state.mut().inner.scratch.runI < state.mut().inner.scratch.runBound; state.mut().inner.scratch.runI++)
        {
        // Every other key stores a deliberate zero.
        state.mut().inner.values.set(state.mut().inner.scratch.runI, QPI::mod(state.mut().inner.scratch.runI, 2ULL) == 0 ? 0 : state.mut().inner.scratch.runI);
        state.mut().inner.present.add(state.mut().inner.scratch.runI);
        }
        for (state.mut().inner.scratch.runI = 0; state.mut().inner.scratch.runI < 1024 + 2; state.mut().inner.scratch.runI++)
        {
        state.mut().inner.scratch.runFetched = 0;
        state.mut().inner.scratch.runHit = state.get().inner.values.get(state.mut().inner.scratch.runI, state.mut().inner.scratch.runFetched) ? 1 : 0;
        state.mut().inner.scratch.runInSet = state.get().inner.present.contains(state.mut().inner.scratch.runI) ? 1 : 0;
        if (state.mut().inner.scratch.runHit != state.mut().inner.scratch.runInSet)
        {
        state.mut().inner.disagreements++;
        }
        if (state.mut().inner.scratch.runHit == 1 && state.mut().inner.scratch.runFetched == 0)
        {
        state.mut().inner.storedZeros++;
        }
        if (state.mut().inner.scratch.runHit == 0)
        {
        state.mut().inner.absent++;
        }
        }
        state.mut().inner.accumulator = state.get().inner.storedZeros * 1000 + state.get().inner.absent;

        state.mut().inner.calls++;
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 accumulator;
        uint64 calls;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.accumulator = state.get().inner.accumulator;
        output.calls = state.get().inner.calls;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }
};
