struct AccountBookWithIterationOrder : public ContractBase
{
    struct StateData
    {
        struct Inner
        {
        uint64 mismatches;
        uint64 sumByInsertion;
        uint64 sumByIteration;
        uint64 length;
        Array<uint64, 8> order;
        HashMap<uint64, uint64, 8> balances;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Credit_input
    {
        uint64 account;
        uint64 amount;
    };

    struct Credit_output {};

    struct Credit_locals
    {
        uint64 current;
        uint64 i;
        uint64 known;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Credit)
    {
        locals.current = 0;
        locals.known = state.get().inner.balances.get(input.account, locals.current) ? 1 : 0;
        state.mut().inner.balances.set(input.account, locals.current + input.amount);
        state.mut().inner.sumByInsertion += input.amount;
        if (locals.known == 0 && state.get().inner.length < 8)
        {
        state.mut().inner.order.set(state.get().inner.length, input.account);
        state.mut().inner.length++;
        }
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        uint64 population;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.length = state.get().inner.length;
        output.sumByIteration = state.get().inner.sumByIteration;
        output.sumByInsertion = state.get().inner.sumByInsertion;
        output.mismatches = state.get().inner.mismatches;
        output.population = state.get().inner.balances.population();
    }

    struct Total_input {};

    struct Total_output {};

    struct Total_locals
    {
        uint64 i;
        uint64 value;
        uint64 running;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Total)
    {
        locals.running = 0;
        for (locals.i = 0; locals.i < state.get().inner.length; locals.i++)
        {
        locals.value = 0;
        state.get().inner.balances.get(state.get().inner.order.get(locals.i), locals.value);
        locals.running += locals.value;
        }
        state.mut().inner.sumByIteration = locals.running;
        if (locals.running != state.get().inner.sumByInsertion)
        {
        state.mut().inner.mismatches++;
        }
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Credit, 1);
        REGISTER_USER_PROCEDURE(Total, 2);
    }
};
