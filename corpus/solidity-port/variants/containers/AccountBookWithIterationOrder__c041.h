struct AccountBookWithIterationOrder : public ContractBase
{
    struct Scratch
    {
        uint64 creditCurrent;
        uint64 creditI;
        uint64 creditKnown;
        uint64 totalI;
        uint64 totalValue;
        uint64 totalRunning;
    };

    struct StateData
    {
        uint64 placementGuard;
        HashMap<uint64, uint64, 8> balances;
        Array<uint64, 8> order;
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        Scratch scratch;
    };

    struct Credit_input
    {
        uint64 account;
        uint64 amount;
    };

    struct Credit_output {};

    struct Credit_locals
    {
        Credit_input forwardedInput;
        Credit_output forwardedOutput;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Credit)
    {
        locals.forwardedInput = input;
        CALL(CreditBody, locals.forwardedInput, locals.forwardedOutput);
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        uint64 population;
    };

    struct Read_locals
    {
        Read_input forwardedInput;
        Read_output forwardedOutput;
    };

    PUBLIC_FUNCTION_WITH_LOCALS(Read)
    {
        CALL(ReadBody, locals.forwardedInput, locals.forwardedOutput);
        output = locals.forwardedOutput;
    }

    struct Total_input {};

    struct Total_output {};

    struct Total_locals
    {
        Total_input forwardedInput;
        Total_output forwardedOutput;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Total)
    {
        CALL(TotalBody, locals.forwardedInput, locals.forwardedOutput);
    }

    using CreditBody_input = Credit_input;

    using CreditBody_output = Credit_output;

    PRIVATE_PROCEDURE(CreditBody)
    {
        state.mut().scratch.creditCurrent = 0;
        state.mut().scratch.creditKnown = state.get().balances.get(input.account, state.mut().scratch.creditCurrent) ? 1 : 0;
        state.mut().balances.set(input.account, state.mut().scratch.creditCurrent + input.amount);
        state.mut().sumByInsertion += input.amount;
        if (state.mut().scratch.creditKnown == 0 && state.get().length < 8)
        {
        state.mut().order.set(state.get().length, input.account);
        state.mut().length++;
        }
    }

    using ReadBody_input = Read_input;

    using ReadBody_output = Read_output;

    PRIVATE_FUNCTION(ReadBody)
    {
        output.length = state.get().length;
        output.sumByIteration = state.get().sumByIteration;
        output.sumByInsertion = state.get().sumByInsertion;
        output.mismatches = state.get().mismatches;
        output.population = state.get().balances.population();
    }

    using TotalBody_input = Total_input;

    using TotalBody_output = Total_output;

    PRIVATE_PROCEDURE(TotalBody)
    {
        state.mut().scratch.totalRunning = 0;
        for (state.mut().scratch.totalI = 0; state.mut().scratch.totalI < state.get().length; state.mut().scratch.totalI++)
        {
        state.mut().scratch.totalValue = 0;
        state.get().balances.get(state.get().order.get(state.mut().scratch.totalI), state.mut().scratch.totalValue);
        state.mut().scratch.totalRunning += state.mut().scratch.totalValue;
        }
        state.mut().sumByIteration = state.mut().scratch.totalRunning;
        if (state.mut().scratch.totalRunning != state.get().sumByInsertion)
        {
        state.mut().mismatches++;
        }
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Credit, 1);
        REGISTER_USER_PROCEDURE(Total, 2);
    }

    INITIALIZE()
    {

    }
};
