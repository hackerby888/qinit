struct MapZeroValueVersusAbsent : public ContractBase
{
    struct Scratch
    {
        uint64 runI;
        uint64 runBound;
        uint64 runFetched;
        uint64 runHit;
        uint64 runInSet;
    };

    struct StateData
    {
        uint64 placementGuard;
        uint64 accumulator;
        uint64 calls;
        HashMap<uint64, uint64, 8> values;
        HashSet<uint64, 8> present;
        uint64 storedZeros;
        uint64 absent;
        uint64 disagreements;
        Scratch scratch;
    };

    struct Run_input
    {
        uint64 count;
        uint64 probe;
    };

    struct Run_output {};

    struct Run_locals
    {
        Run_input forwardedInput;
        Run_output forwardedOutput;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Run)
    {
        locals.forwardedInput = input;
        CALL(RunBody, locals.forwardedInput, locals.forwardedOutput);
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 accumulator;
        uint64 calls;
    };

    struct Read_locals
    {
        Read_input forwardedInput;
        Read_output forwardedOutput;
    };

    PUBLIC_FUNCTION_WITH_LOCALS(Read)
    {
        CALL(ReadBody, locals.forwardedInput, locals.forwardedOutput);
        output = locals.forwardedOutput;
    }

    using RunBody_input = Run_input;

    using RunBody_output = Run_output;

    PRIVATE_PROCEDURE(RunBody)
    {
        state.mut().scratch.runBound = input.count;
        if (state.mut().scratch.runBound > 8)
        {
        state.mut().scratch.runBound = 8;
        }
        state.mut().values.reset();
        state.mut().present.reset();
        state.mut().storedZeros = 0;
        state.mut().absent = 0;
        for (state.mut().scratch.runI = 0; state.mut().scratch.runI < state.mut().scratch.runBound; state.mut().scratch.runI++)
        {
        // Every other key stores a deliberate zero.
        state.mut().values.set(state.mut().scratch.runI, QPI::mod(state.mut().scratch.runI, 2ULL) == 0 ? 0 : state.mut().scratch.runI);
        state.mut().present.add(state.mut().scratch.runI);
        }
        for (state.mut().scratch.runI = 0; state.mut().scratch.runI < 8 + 2; state.mut().scratch.runI++)
        {
        state.mut().scratch.runFetched = 0;
        state.mut().scratch.runHit = state.get().values.get(state.mut().scratch.runI, state.mut().scratch.runFetched) ? 1 : 0;
        state.mut().scratch.runInSet = state.get().present.contains(state.mut().scratch.runI) ? 1 : 0;
        if (state.mut().scratch.runHit != state.mut().scratch.runInSet)
        {
        state.mut().disagreements++;
        }
        if (state.mut().scratch.runHit == 1 && state.mut().scratch.runFetched == 0)
        {
        state.mut().storedZeros++;
        }
        if (state.mut().scratch.runHit == 0)
        {
        state.mut().absent++;
        }
        }
        state.mut().accumulator = state.get().storedZeros * 1000 + state.get().absent;

        state.mut().calls++;
    }

    using ReadBody_input = Read_input;

    using ReadBody_output = Read_output;

    PRIVATE_FUNCTION(ReadBody)
    {
        output.accumulator = state.get().accumulator;
        output.calls = state.get().calls;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }

    INITIALIZE()
    {
        state.mut().accumulator = 0;
        state.mut().calls = 0;
    }
};
