struct AccountBookWithIterationOrder : public ContractBase
{
    struct Scratch
    {
        uint64 creditCurrent;
        uint64 creditI;
        uint64 creditKnown;
        uint64 totalI;
        uint64 totalValue;
        uint64 totalRunning;
    };

    struct StateData
    {
        struct Inner
        {
        HashMap<uint64, uint64, 2> balances;
        Array<uint64, 2> order;
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        Scratch scratch;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Total_input {};

    struct Total_output {};

    PUBLIC_PROCEDURE(Total)
    {
        state.mut().inner.scratch.totalRunning = 0;
        for (state.mut().inner.scratch.totalI = 0; state.mut().inner.scratch.totalI < state.get().inner.length; state.mut().inner.scratch.totalI++)
        {
        state.mut().inner.scratch.totalValue = 0;
        state.get().inner.balances.get(state.get().inner.order.get(state.mut().inner.scratch.totalI), state.mut().inner.scratch.totalValue);
        state.mut().inner.scratch.totalRunning += state.mut().inner.scratch.totalValue;
        }
        state.mut().inner.sumByIteration = state.mut().inner.scratch.totalRunning;
        if (state.mut().inner.scratch.totalRunning != state.get().inner.sumByInsertion)
        {
        state.mut().inner.mismatches++;
        }
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        uint64 population;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.length = state.get().inner.length;
        output.sumByIteration = state.get().inner.sumByIteration;
        output.sumByInsertion = state.get().inner.sumByInsertion;
        output.mismatches = state.get().inner.mismatches;
        output.population = state.get().inner.balances.population();
    }

    struct Credit_input
    {
        uint64 account;
        uint64 amount;
    };

    struct Credit_output {};

    PUBLIC_PROCEDURE(Credit)
    {
        state.mut().inner.scratch.creditCurrent = 0;
        state.mut().inner.scratch.creditKnown = state.get().inner.balances.get(input.account, state.mut().inner.scratch.creditCurrent) ? 1 : 0;
        state.mut().inner.balances.set(input.account, state.mut().inner.scratch.creditCurrent + input.amount);
        state.mut().inner.sumByInsertion += input.amount;
        if (state.mut().inner.scratch.creditKnown == 0 && state.get().inner.length < 2)
        {
        state.mut().inner.order.set(state.get().inner.length, input.account);
        state.mut().inner.length++;
        }
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Credit, 1);
        REGISTER_USER_PROCEDURE(Total, 2);
    }

    INITIALIZE()
    {

    }
};
