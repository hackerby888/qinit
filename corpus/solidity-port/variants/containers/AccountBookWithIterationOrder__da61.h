struct AccountBookWithIterationOrder : public ContractBase
{
    struct Scratch
    {
        uint64 creditCurrent;
        uint64 creditI;
        uint64 creditKnown;
        uint64 totalI;
        uint64 totalValue;
        uint64 totalRunning;
    };

    struct StateData
    {
        uint64 mismatches;
        uint64 sumByInsertion;
        uint64 sumByIteration;
        uint64 length;
        Array<uint64, 1024> order;
        HashMap<uint64, uint64, 1024> balances;
        Scratch scratch;
        uint64 placementGuard;
    };

    struct Total_input {};

    struct Total_output {};

    PUBLIC_PROCEDURE(Total)
    {
        state.mut().scratch.totalRunning = 0;
        for (state.mut().scratch.totalI = 0; state.mut().scratch.totalI < state.get().length; state.mut().scratch.totalI++)
        {
        state.mut().scratch.totalValue = 0;
        state.get().balances.get(state.get().order.get(state.mut().scratch.totalI), state.mut().scratch.totalValue);
        state.mut().scratch.totalRunning += state.mut().scratch.totalValue;
        }
        state.mut().sumByIteration = state.mut().scratch.totalRunning;
        if (state.mut().scratch.totalRunning != state.get().sumByInsertion)
        {
        state.mut().mismatches++;
        }
    }

    struct Read_input {};

    struct Read_output
    {
        uint64 length;
        uint64 sumByIteration;
        uint64 sumByInsertion;
        uint64 mismatches;
        uint64 population;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.length = state.get().length;
        output.sumByIteration = state.get().sumByIteration;
        output.sumByInsertion = state.get().sumByInsertion;
        output.mismatches = state.get().mismatches;
        output.population = state.get().balances.population();
    }

    struct Credit_input
    {
        uint64 account;
        uint64 amount;
    };

    struct Credit_output {};

    PUBLIC_PROCEDURE(Credit)
    {
        state.mut().scratch.creditCurrent = 0;
        state.mut().scratch.creditKnown = state.get().balances.get(input.account, state.mut().scratch.creditCurrent) ? 1 : 0;
        state.mut().balances.set(input.account, state.mut().scratch.creditCurrent + input.amount);
        state.mut().sumByInsertion += input.amount;
        if (state.mut().scratch.creditKnown == 0 && state.get().length < 1024)
        {
        state.mut().order.set(state.get().length, input.account);
        state.mut().length++;
        }
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Credit, 1);
        REGISTER_USER_PROCEDURE(Total, 2);
    }

    INITIALIZE()
    {
        state.mut().balances.reset();
        state.mut().order.setAll(0);
        state.mut().length = 0;
        state.mut().sumByIteration = 0;
        state.mut().sumByInsertion = 0;
        state.mut().mismatches = 0;
    }
};
