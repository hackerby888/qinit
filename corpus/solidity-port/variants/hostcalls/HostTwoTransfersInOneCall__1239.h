// Stresses: two transfers in one procedure, where the second sees whatever balance the first left — the returned remaining amounts have to decrease in step
// Port caveat: The typed transfer (`__transfer`) is not reachable from a contract: QPI's source policy forbids double-underscore names, and both backends refuse it. So this archetype uses the plain call twice.
// Variant: entryOrder=reversed entryShape=direct initStyle=full placement=nested stateOrder=declared temporaries=stateScratch
// Generated by scripts/solidity-port/generate.ts. Do not edit; edit the archetype instead.
using namespace QPI;

