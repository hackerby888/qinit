struct HostTwoTransfersInOneCall : public ContractBase
{
    struct StateData
    {
        struct Inner
        {
        uint64 calls;
        sint64 rewardSeen;
        uint64 bothSucceeded;
        sint64 secondResult;
        sint64 plainResult;
        };
        uint64 placementGuard;
        Inner inner;
    };

    struct Run_input
    {
        uint64 a;
        uint64 b;
    };

    struct Run_output {};

    struct Run_locals
    {
        id target;
        sint64 amount;
    };

    PUBLIC_PROCEDURE_WITH_LOCALS(Run)
    {
        state.mut().inner.rewardSeen += qpi.invocationReward();
        locals.target = qpi.K12(input.a);
        locals.amount = (sint64)QPI::mod(input.b, 1000ULL);
        state.mut().inner.plainResult = qpi.transfer(locals.target, locals.amount);
        state.mut().inner.secondResult = qpi.transfer(locals.target, locals.amount);
        state.mut().inner.bothSucceeded = state.get().inner.plainResult >= 0 && state.get().inner.secondResult >= 0 ? 1 : 0;

        state.mut().inner.calls++;
    }

    struct Read_input {};

    struct Read_output
    {
        sint64 plainResult;
        sint64 secondResult;
        uint64 bothSucceeded;
        sint64 rewardSeen;
        uint64 calls;
    };

    PUBLIC_FUNCTION(Read)
    {
        output.plainResult = state.get().inner.plainResult;
        output.secondResult = state.get().inner.secondResult;
        output.bothSucceeded = state.get().inner.bothSucceeded;
        output.rewardSeen = state.get().inner.rewardSeen;
        output.calls = state.get().inner.calls;
    }

    REGISTER_USER_FUNCTIONS_AND_PROCEDURES()
    {
        REGISTER_USER_FUNCTION(Read, 1);
        REGISTER_USER_PROCEDURE(Run, 1);
    }
};
