// Generates the simulator's default committee: 676 deterministic dev seeds with their FourQ keys precomputed, so constructing a
// simulator costs a table lookup instead of 676 key derivations. Run: bun packages/engine/tools/gen-default-committee.ts
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { bytesToHex, deriveKeysSync, initK12, k12Sync } from "@qinit/core";

const SEATS = 676;
const ALPHABET = "abcdefghijklmnopqrstuvwxyz";

// 55 letters from two K12 blocks over the seat's label: fixed, distinct, and obviously not anyone's wallet.
function seatSeed(index: number): string {
    const label = new TextEncoder().encode(`qinit default committee seat ${index}`);
    const bytes = new Uint8Array([...k12Sync(new Uint8Array([...label, 0])), ...k12Sync(new Uint8Array([...label, 1]))]);
    return Array.from(bytes.subarray(0, 55), (byte) => ALPHABET[byte % 26]).join("");
}

await initK12();
const rows = Array.from({ length: SEATS }, (_, index) => {
    const seed = seatSeed(index);
    const keys = deriveKeysSync(seed);
    return `    ["${seed}", "${bytesToHex(keys.publicKey)}", "${bytesToHex(keys.privateKey)}"],`;
});
const output = resolve(import.meta.dir, "..", "src", "chain", "generated", "default-committee.ts");
writeFileSync(
    output,
    "// Generated by tools/gen-default-committee.ts — do not edit. seed, public key, private key (FourQ subseed) per seat.\n" +
        "export const DEFAULT_COMMITTEE: readonly (readonly [string, string, string])[] = [\n" +
        rows.join("\n") +
        "\n];\n",
);
console.log(`${output}: ${SEATS} seats`);
