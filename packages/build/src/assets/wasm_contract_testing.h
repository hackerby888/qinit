// Identity (56 A-Z chars + 4-char checksum) -> 32-byte public key: base26 decode, 14 chars per 64-bit limb,
// little-endian; the trailing checksum chars are not needed to recover the key. Mirrors core-lite four_q.h
static inline bool getPublicKeyFromIdentity(const unsigned char* identity, unsigned char* publicKey) {
    for (int i = 0; i < 4; i++) {
        unsigned long long limb = 0;
        for (int j = 14; j-- > 0; ) {
            unsigned char c = identity[i * 14 + j];
            if (c < 'A' || c > 'Z') {
                return false;
            }
            limb = limb * 26 + (unsigned long long)(c - 'A');
        }
        for (int b = 0; b < 8; b++) {
            publicKey[(i << 3) + b] = (unsigned char)(limb >> (8 * b));
        }
    }
    return true;
}

// core's test_util.h streams an id as its 60-char identity; the checksum is the host's k12 of the key, as four_q.h getIdentity computes it.
static std::ostream& operator<<(std::ostream& s, const m256i& v) {
    char identity[61];
    for (int i = 0; i < 4; i++) {
        unsigned long long fragment;
        copyMem(&fragment, &v.m256i_u8[i << 3], 8);
        for (int j = 0; j < 14; j++) {
            identity[i * 14 + j] = (char)('A' + fragment % 26);
            fragment /= 26;
        }
    }
    unsigned char digest[32];
    lh_k12(v.m256i_u8, 32, digest);
    unsigned int checksum = ((unsigned int)digest[0] | ((unsigned int)digest[1] << 8) | ((unsigned int)digest[2] << 16)) & 0x3FFFF;
    for (int i = 0; i < 4; i++) {
        identity[56 + i] = (char)('A' + checksum % 26);
        checksum /= 26;
    }
    identity[60] = 0;
    return s << identity;
}

